  // Пункты договора с позициями в тексте: строки, а внутри строки — предложения
  function clauses(text) {
    const out = [];
    for (const line of text.matchAll(/[^\n]+/g)) {
      const parts = line[0].split(/(?<=[.;!?])\s+(?=[A-ZА-ЯЁӘҒҚҢӨҰҮҺІ«"(])/u);
      let pos = line.index;
      for (const p of parts) {
        const s = text.indexOf(p, pos);
        out.push({ s, e: s + p.length, text: p });
        pos = s + p.length;
      }
    }
    return out;
  }

  // Все найденные риски: [{ s, e, rule }]; у одного пункта может быть несколько рисков
  window.AB_findRisks = (text) => {
    const hits = [];
    for (const c of clauses(text)) {
      if (!c.text.trim()) continue;
      for (const rule of window.AB_RULES) {
        const ok = rule.pat.some((p) =>
          p.all.every((re) => re.test(c.text)) &&
          !(p.none || []).some((re) => re.test(c.text)) &&
          (!p.test || p.test(c.text)));
        if (ok) hits.push({ s: c.s, e: c.e, rule });
      }
    }
    return hits;
  };
